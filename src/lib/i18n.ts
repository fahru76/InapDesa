const DICTS: Record<Locale, Record<MessageKey, string>> = { en, ms };

export type TParams = Record<string, string | number>;

export function translate(locale: Locale, key: MessageKey, params?: TParams): string {
  const template = DICTS[locale][key] ?? en[key];
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (_, k: string) => (k in params ? String(params[k]) : `{${k}}`));
}

/** Pick `.one` / `.other` variants by count. */
export function translatePlural(locale: Locale, base: string, n: number, params?: TParams): string {
  const key = `${base}.${n === 1 ? "one" : "other"}` as MessageKey;
  return translate(locale, key, { n, ...params });
}

export interface T {
  (key: MessageKey, params?: TParams): string;
  plural: (base: string, n: number, params?: TParams) => string;
  locale: Locale;
}

export function makeT(locale: Locale): T {
  const fn = ((key: MessageKey, params?: TParams) => translate(locale, key, params)) as T;
  fn.plural = (base, n, params) => translatePlural(locale, base, n, params);
  fn.locale = locale;
  return fn;
}

/** Intl locale tag for dates/numbers. */
export function intlLocale(locale: Locale): string {
  return locale === "ms" ? "ms-MY" : "en-MY";
}

